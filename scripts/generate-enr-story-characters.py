"""Generate the Enemy Randomization story-character Mirror exclusion catalog.

Mirror clones spawn from the root template with a new GUID, so story rules
keyed on a placed character's GUID never fire for the clone. The catalog
lists the placed characters where a duplicate is still risky:

* characters the Osiris story references on a death/kill line, whose fight
  or quest the story resolves by script; and
* dummy, placeholder, cinematic, and vocal-component stand-ins, whose
  templates are not meant to spawn on their own.

Usage (from the repository root, Windows/Git Bash):

    python scripts/generate-enr-story-characters.py

Required extracted sources (paths must be absolute for Divine.exe):

    D=tools/lslib/Packed/Tools
    DATA="<BG3>/Data"
    OUT="$PWD/.analysis"
    $D/Divine.exe -g bg3 -a extract-package -s "$DATA/Patch8_HotFix10.pak" \\
        -d "$OUT/pak" --use-regex -x 'Mods/GustavX/Story/story\\.div\\.osi'
    $D/Divine.exe -g bg3 -a extract-package -s "$DATA/Gustav.pak" \\
        -d "$OUT/pak" --use-regex -x '.*/(Globals|Levels)/[^/]+/Characters/_merged\\.lsf$'
    $D/Divine.exe -g bg3 -a extract-package -s "$DATA/Shared.pak" \\
        -d "$OUT/pak" --use-regex -x '.*/(Globals|Levels)/[^/]+/Characters/_merged\\.lsf$'
    $D/Divine.exe -g bg3 -a convert-resources -s "$OUT/pak" -d "$OUT/lsx" -i lsf -o lsx
    mkdir -p "$OUT/story/goals"
    $D/StoryDecompiler.exe --input "$OUT/pak/Mods/GustavX/Story/story.div.osi" \\
        --output "$OUT/story/goals"

Use the newest hotfix pak that contains GustavX/story.div.osi.
"""

from __future__ import annotations

import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = (
    ROOT
    / "mods"
    / "EnemyRandomization"
    / "Mods"
    / "EnemyRandomization"
    / "ScriptExtender"
    / "Lua"
    / "Server"
    / "GeneratedStoryCharacters.lua"
)

GUID = r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}"
GUID_RE = re.compile(GUID)
DEATH_LINE_RE = re.compile(r"Died|Dying|DB_Dead|Killed|DeathEvent|_Death")
STAND_IN_NAME_RE = re.compile(r"Dummy|Placeholder|Vocals_|_CIN_|Cinematic", re.I)
STAND_IN_LEVEL_RE = re.compile(r"_CIN_|SpellVocalComponent", re.I)


def _goal_dir() -> Path:
    return ROOT / ".analysis" / "story" / "goals"


def _character_files() -> list[Path]:
    return sorted((ROOT / ".analysis" / "lsx").glob("**/Characters/_merged.lsx"))


def load_placed_characters() -> dict[str, dict[str, str]]:
    """Return placed characters keyed by lowercase MapKey GUID."""
    placed: dict[str, dict[str, str]] = {}
    for path in _character_files():
        for node in ET.parse(path).getroot().iter("node"):
            if node.get("id") != "GameObjects":
                continue
            attrs = {a.get("id"): a.get("value") or "" for a in node.findall("attribute")}
            key = attrs.get("MapKey", "").lower()
            if attrs.get("Type") != "character" or not GUID_RE.fullmatch(key):
                continue
            placed[key] = {
                "name": attrs.get("Name", ""),
                "level": attrs.get("LevelName", ""),
            }
    return placed


def death_line_guids() -> set[str]:
    guids: set[str] = set()
    for path in sorted(_goal_dir().glob("*.txt")):
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            if DEATH_LINE_RE.search(line):
                guids.update(GUID_RE.findall(line.lower()))
    return guids


def is_stand_in(character: dict[str, str]) -> bool:
    return bool(
        STAND_IN_NAME_RE.search(character["name"]) or STAND_IN_LEVEL_RE.search(character["level"])
    )


def build_catalog(placed: dict[str, dict[str, str]], death: set[str]) -> dict[str, str]:
    """Return GUID -> reason ("death" or "stand_in") for excluded characters."""
    catalog: dict[str, str] = {}
    for guid, character in placed.items():
        if is_stand_in(character):
            catalog[guid] = "stand_in"
        elif guid in death:
            catalog[guid] = "death"
    return catalog


def render(catalog: dict[str, str], placed: dict[str, dict[str, str]]) -> str:
    counts = {reason: sum(1 for r in catalog.values() if r == reason) for reason in ("death", "stand_in")}
    lines = [
        "-- Generated by scripts/generate-enr-story-characters.py. Do not edit by hand.",
        "-- Placed characters Mirror never clones: story death/kill-line references",
        "-- (%d) and dummy/placeholder/cinematic/vocal stand-ins (%d)." % (counts["death"], counts["stand_in"]),
        "-- Add manual exclusions to Config.MIRROR_EXCLUDE instead.",
        "",
        "ER = ER or {}",
        "ER.GeneratedStoryCharacters = {",
    ]
    for guid in sorted(catalog):
        lines.append(
            "    [%s] = %s, -- %s"
            % (json.dumps(guid), json.dumps(catalog[guid]), placed[guid]["name"] or "?")
        )
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> None:
    if not _goal_dir().is_dir() or not _character_files():
        print("story goals or character LSX missing; keeping committed %s" % OUT.name)
        return
    placed = load_placed_characters()
    catalog = build_catalog(placed, death_line_guids())
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(catalog, placed), encoding="utf-8")
    print("placed characters: %d, excluded: %d" % (len(placed), len(catalog)))
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()
