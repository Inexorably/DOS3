"""CC_Ladder_SE's Lua under DOS3's own harness (lua_stub.lua, lupa, LuaCov): a generator over the mod's modules + the
behaviour sims that BG3_MODS runs on this same Lua, ported unchanged (tests/fixtures/cc_ladder_se/). Each sim case must print byte
for byte what it printed in BG3_MODS (cases.json: sha256[:16] of the output). Generated by BG3_MODS `bg3gen outbox mod`.
"""

from __future__ import annotations

import hashlib
import json
import unittest

from .lua_harness import LuaModHarness, lua_mod_root
from .support import ROOT, lua_runtime, read

try:
    import lupa  # noqa: F401

    HAVE_LUPA = True
except ImportError:  # pragma: no cover
    HAVE_LUPA = False

FOLDER = "CC_Ladder_SE"
LUA = lua_mod_root(FOLDER)
FIXTURES = ROOT / "tests" / "fixtures" / "cc_ladder_se"
DOC = json.loads(read(FIXTURES / "cases.json"))
BOOTS = [m for m in DOC["modules"] if m.startswith("Bootstrap")]

# the sims' dofile + print: a mod file loads as "@<path>" (LuaCov counts it), a fixture or a data override as "=<name>"
SETUP = """
local fixtures, data = ...
dofile = function(path)
  local name = path:match("[^/]+$")
  local text = data[name]
  local chunk = "=" .. name
  if text == nil then
    local f = assert(io.open(path, "rb"))
    text = f:read("a")
    f:close()
    if path:sub(1, #fixtures) ~= fixtures then chunk = "@" .. path end
  end
  return assert(load(text, chunk))()
end
OUT = {}
print = function(...)
  local t = table.pack(...)
  for i = 1, t.n do t[i] = tostring(t[i]) end
  OUT[#OUT + 1] = table.concat(t, "\\t", 1, t.n)
end
"""


def run_case(case: dict) -> str:
    """one sim case in a fresh DOS3 Lua runtime; its whole stdout."""
    lua = lua_runtime()
    lua.execute(SETUP, FIXTURES.as_posix(), lua.table_from(case["data"]))
    arg = lua.table()
    arg[0] = (FIXTURES / case["sim"]).as_posix()
    arg[1] = LUA.resolve().as_posix()
    if case["mode"]:
        arg[2] = case["mode"]
    lua.globals().arg = arg
    lua.eval('function(text) return assert(load(text, "=sim"))() end')(read(FIXTURES / case["sim"]))
    return "".join(line + "\n" for line in lua.globals().OUT.values())


@unittest.skipUnless(HAVE_LUPA, "lupa is required for Lua module tests")
class CcLadderSeLuaTests(unittest.TestCase):
    def test_modules_are_the_mod_folder(self) -> None:
        self.assertEqual(DOC["modules"], sorted(p.name for p in LUA.glob("*.lua")))

    def test_bootstraps_require_every_module(self) -> None:
        required: set[str] = set()
        for boot in BOOTS:
            harness = LuaModHarness(FOLDER)
            harness.load_bootstrap(boot)
            required |= set(harness.requires())
        self.assertEqual(required, set(DOC["modules"]) - set(BOOTS))


def _module_test(module: str):
    def test(self: unittest.TestCase) -> None:
        self.assertTrue(any(module in case["files"] for case in DOC["cases"]), module)
    return test


def _case_test(case: dict):
    def test(self: unittest.TestCase) -> None:
        out = run_case(case)
        self.assertNotIn("SIM ERROR", out)
        self.assertEqual(hashlib.sha256(out.encode("utf-8")).hexdigest()[:16], case["sha16"], out[-2000:])
    return test


for _module in DOC["modules"]:
    if _module not in BOOTS:
        setattr(CcLadderSeLuaTests, "test_module_" + _module[:-4] + "_runs_in_a_case", _module_test(_module))
for _case in DOC["cases"]:
    setattr(CcLadderSeLuaTests, "test_sim_" + _case["name"], _case_test(_case))
